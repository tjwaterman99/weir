//! Generates the command reference of the documentation site from the same
//! definitions the command line is parsed with, so the two cannot drift.

use anyhow::{Context, Result};
use std::path::Path;

use crate::settings::SETTINGS;

const NOTICE: &str = "<!-- Generated by `weir reference`. Do not edit: change the help text in src/main.rs and regenerate. -->";

fn help(cmd: &clap::Command) -> String {
    let text = cmd.clone().render_long_help().to_string();
    // Trailing spaces in clap's output would only make noisy diffs.
    text.lines()
        .map(str::trim_end)
        .collect::<Vec<_>>()
        .join("\n")
        .trim()
        .to_string()
}

fn about(cmd: &clap::Command) -> String {
    cmd.get_about().map(|a| a.to_string()).unwrap_or_default()
}

/// Writes one page per command into `dir`, plus `index.md` and `settings.md`.
/// A command with a file in `examples` gets that file included in its page.
pub fn write(mut root: clap::Command, dir: &Path, examples: &Path) -> Result<()> {
    root.build();
    std::fs::create_dir_all(dir).with_context(|| format!("could not create {}", dir.display()))?;
    for entry in std::fs::read_dir(dir)?.flatten() {
        if entry.path().extension().is_some_and(|e| e == "md") {
            std::fs::remove_file(entry.path())?;
        }
    }

    let mut index = format!(
        "# Commands\n\n{NOTICE}\n\nEvery command, with the page that describes it.\n\n| Command | What it does |\n|---|---|\n"
    );
    for cmd in root.get_subcommands().filter(|c| !c.is_hide_set()) {
        let name = cmd.get_name();
        index.push_str(&format!(
            "| [`weir {name}`]({name}.md) | {} |\n",
            about(cmd)
        ));

        let mut page = format!(
            "# weir {name}\n\n{NOTICE}\n\n{}.\n\n```text\n{}\n```\n",
            about(cmd).trim_end_matches('.'),
            help(cmd)
        );
        for sub in cmd.get_subcommands().filter(|c| !c.is_hide_set()) {
            page.push_str(&format!(
                "\n## weir {name} {}\n\n{}.\n\n```text\n{}\n```\n",
                sub.get_name(),
                about(sub).trim_end_matches('.'),
                help(sub)
            ));
        }
        if examples.join(format!("{name}.md")).exists() {
            page.push_str(&format!("\n{{{{#include ../../examples/{name}.md}}}}\n"));
        }
        std::fs::write(dir.join(format!("{name}.md")), page)?;
    }
    index.push_str(
        "\n## Options every command accepts\n\n| Option | Meaning |\n|---|---|\n| `--json` | Machine-readable output, where the command has any |\n| `-q`, `--quiet` | Print errors only |\n| `-h`, `--help` | Explain the command |\n\n## Exit codes\n\n| Code | Meaning |\n|---|---|\n| `0` | Everything is in order |\n| `1` | It ran, and something needs attention (a repository failed or was skipped, an account was rejected, syncs are stale) |\n| `2` | It could not run (bad arguments, nothing tracked, a database error) |\n",
    );
    std::fs::write(dir.join("index.md"), index)?;

    let mut settings = format!(
        "# Settings\n\n{NOTICE}\n\nSettings live in weir's database. Read and change them with `weir config`:\n\n```text\nweir config list\nweir config set <setting> <value>\nweir config unset <setting>\n```\n\n| Setting | Default | Meaning |\n|---|---|---|\n"
    );
    for s in &SETTINGS {
        let default = if s.default.is_empty() {
            "(not set)".to_string()
        } else {
            format!("`{}`", s.default)
        };
        settings.push_str(&format!("| `{}` | {default} | {} |\n", s.key, s.help));
    }
    std::fs::write(dir.join("settings.md"), settings)?;
    Ok(())
}
